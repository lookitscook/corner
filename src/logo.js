export const LOGO_DEFAULTS = Object.freeze({ logoEnabled: true, logoX: .98, logoY: .98, logoSize: 20 });
export function readLogoSettings(settings) {
  const result = {};
  for (const [key, fallback] of Object.entries(LOGO_DEFAULTS)) {
    const value = settings[key] === undefined ? fallback : settings[key];
    const valid = key === 'logoEnabled' ? typeof value === 'boolean' : Number.isFinite(value) &&
      (key === 'logoSize' ? value >= 4 && value <= 80 : value >= 0 && value <= 1);
    if (!valid) throw new Error(`Invalid ${key} setting.`);
    result[key] = value;
  }
  return result;
}

export function logoBox(width, height, settings) {
  const size = Math.min(width, height) * settings.logoSize / 100;
  return { x: Math.max(0, Math.min(width - size, settings.logoX * width - size)),
    y: Math.max(0, Math.min(height - size, settings.logoY * height - size)), size };
}
